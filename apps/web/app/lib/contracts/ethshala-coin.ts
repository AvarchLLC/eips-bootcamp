/**
 * Format raw 18-decimal token wei to human readable string
 */
export function formatEshc(valueInWei: bigint | string | number): string {
  try {
    const bigVal = BigInt(valueInWei.toString());
    const whole = bigVal / BigInt(10 ** 18);
    return whole.toLocaleString();
  } catch {
    return '0';
  }
}

/**
 * Parse human readable ESHC count to 18-decimal token wei
 */
export function parseEshc(tokens: number | string): bigint {
  try {
    const count = typeof tokens === 'string' ? parseFloat(tokens) : tokens;
    return BigInt(Math.floor(count)) * BigInt(10 ** 18);
  } catch {
    return BigInt(0);
  }
}
